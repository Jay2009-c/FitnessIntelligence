package com.example.fitnessanalyzer.data.local

import androidx.room.Entity
import androidx.room.PrimaryKey
import com.example.fitnessanalyzer.domain.model.*

@Entity(tableName = "local_workouts")
data class WorkoutSessionEntity(
    @PrimaryKey val id: String,
    val sourcePackage: String?,
    val startTimeMillis: Long,
    val endTimeMillis: Long,
    val durationSeconds: Long,
    val workoutType: WorkoutType,
    val age: Int?,
    val weightKg: Float?,
    val heightCm: Float?,
    val isMale: Boolean?,
    val restingHeartRate: Int?,
    val estimatedMaxHeartRate: Int?,
    val averageHeartRate: Float?,
    val peakHeartRate: Int?,
    val caloriesKcal: Float?,
    val distanceMeters: Float?,
    val totalSteps: Int?,
    val averagePaceMinPerKm: Float?,
    val bestPaceMinPerKm: Float?,
    val averageCadence: Float?,
    val averageStrideLengthMeters: Float?,
    val elevationGainedMeters: Float?,
    val averagePowerWatts: Float?,
    val maxPowerWatts: Float?,
    val sensorQuality: SensorQuality,
    val heartRateSamples: List<HeartRateSample>,
    val paceSamples: List<PaceSample>,
    val stepSamples: List<StepSample>,
    val estimatedVo2Max: Float?,
    val cooperVo2Max: Float?,
    val uthVo2Max: Float?,
    val acsmVo2Max: Float?,
    val friendVo2Max: Float?,
    val trimpScore: Float?,
    val edwardsTrimp: Float?,
    val luciaTrimp: Float?,
    val strainScore: Float?,
    val estimatedRecoveryHours: Int?,
    val heartRateRecovery: Int?,
    val readinessScore: Float?,
    val aerobicEfficiency: Float?,
    val heartRateDriftPercent: Float?,
    val aerobicLoad: Float?,
    val anaerobicLoad: Float?,
    val trainingEffectLabel: String?,
    val hrZoneDistribution: HrZoneDistribution?,
    val paceZoneDistribution: PaceZoneDistribution?,
    val confidenceScore: Float,
    val hasMissingHeartRateData: Boolean,
    val hasGpsDropouts: Boolean,
    val containsOutlierData: Boolean,
    val notes: String?
)

